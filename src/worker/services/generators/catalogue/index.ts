const GENERATOR_TOOLS = createGeneratorTools();

const GENERATOR_LOOKUP = new Map<string, GeneratorTool>(
	GENERATOR_TOOLS.flatMap((generator) =>
		[generator.id, ...generator.aliases].map((key): [string, GeneratorTool] => [key, generator]),
	),
);

export function findGenerator(type: string) {
	return GENERATOR_LOOKUP.get(type.trim().toLowerCase());
}

export function listGeneratorTools() {
	return GENERATOR_TOOLS;
}

function tool(
	id: string,
	label: string,
	audience: Audience,
	description: string,
	inputLabel: string,
	required: boolean,
	placeholder: string,
	resultKind: ResultKind,
	actionLabel: string,
	examples: readonly ToolExample[],
	fields?: readonly GeneratorInputField[],
): GeneratorTool {
	return {
		aliases: GENERATOR_ALIASES[id] ?? [],
		audience,
		description,
		display: {
			actionLabel,
			category: CATEGORY_LABELS[audience],
			examples,
		},
		endpoint: `/api/${id}`,
		id,
		input: {
			fields,
			label: inputLabel,
			mode: NO_INPUT_TOOL_IDS.has(id) ? "none" : "text",
			required,
		},
		label,
		modes: resultKind === "image" ? [] : ["ai"],
		placeholder,
		result: { kind: resultKind },
	};
}

function field(
	id: string,
	label: string,
	placeholder: string,
	required: boolean,
	type: GeneratorInputField["type"] = "text",
	options?: readonly string[],
): GeneratorInputField {
	return { id, label, options, placeholder, required, type };
}

function shownWhen(
	definition: GeneratorInputField,
	field: string,
	values: readonly string[],
): GeneratorInputField {
	return { ...definition, visibleWhen: { field, values } };
}
